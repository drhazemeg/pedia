// src/routers/auth.ts

import { ORPCError } from "@orpc/server";
import { auth } from "@pedia/auth";
import { authRepository } from "@pedia/db/repositories";
import { createId } from "@pedia/shared";
import { z } from "zod/v4";

import { adminProcedure, publicProcedure } from "../index";

// ─── Schemas ───
const loginSchema = z.object({
  email: z.email("Invalid email format"),
  password: z.string().min(8, "Password must be at least 8 characters"),
});

const registerSchema = z.object({
  name: z.string().min(2, "Name must be at least 2 characters"),
  email: z.email("Invalid email format"),
  password: z
    .string()
    .min(8, "Password must be at least 8 characters")
    .regex(/[A-Z]/, "Password must contain at least one uppercase letter")
    .regex(/[a-z]/, "Password must contain at least one lowercase letter")
    .regex(/[0-9]/, "Password must contain at least one number")
    .regex(
      /[^A-Za-z0-9]/,
      "Password must contain at least one special character"
    ),
  role: z
    .enum(["admin", "doctor", "staff", "patient"])
    .optional()
    .default("patient"),
  acceptTerms: z
    .boolean()
    .refine((val) => val === true, "You must accept the terms and conditions"),
});

const resetPasswordSchema = z.object({
  email: z.email("Invalid email format"),
});

const changePasswordSchema = z.object({
  currentPassword: z.string().min(1, "Current password is required"),
  newPassword: z
    .string()
    .min(8, "Password must be at least 8 characters")
    .regex(/[A-Z]/, "Password must contain at least one uppercase letter")
    .regex(/[a-z]/, "Password must contain at least one lowercase letter")
    .regex(/[0-9]/, "Password must contain at least one number")
    .regex(
      /[^A-Za-z0-9]/,
      "Password must contain at least one special character"
    ),
});

const updateUserSchema = z.object({
  name: z.string().min(2, "Name must be at least 2 characters").optional(),
  email: z.email("Invalid email format").optional(),
  phone: z.string().optional(),
  profilePicture: z.url("Invalid URL").optional(),
  preferences: z.record(z.any(), z.any()).optional(),
});

const twoFactorVerifySchema = z.object({
  token: z
    .string()
    .length(6, "Token must be 6 digits")
    .regex(/^\d+$/, "Token must contain only numbers"),
});

const twoFactorDisableSchema = z.object({
  token: z
    .string()
    .length(6, "Token must be 6 digits")
    .regex(/^\d+$/, "Token must contain only numbers"),
});

export const authRouter = {
  // ─── Public Routes ───

  login: publicProcedure
    .input(loginSchema)
    .handler(async ({ input, context }) => {
      try {
        // CORRECT - server-side requires body: { ... }
        const result = await auth.api.signInEmail({
          body: {
            email: input.email,
            password: input.password,
          },
          // This endpoint requires session cookies
          headers: context.request?.headers,
        });
        if (!result) {
          throw new ORPCError("UNAUTHORIZED", {
            message: "Invalid email or password",
          });
        }
        return result;
      } catch (error) {
        if (error instanceof ORPCError) throw error;
        throw new ORPCError("INTERNAL_SERVER_ERROR", {
          message: "Login failed. Please try again.",
          cause: error,
        });
      }
    }),

  register: publicProcedure.input(registerSchema).handler(async ({ input }) => {
    try {
      // Check if user already exists
      const existingUser = await authRepository.findUserByEmail(input.email);
      if (existingUser) {
        throw new ORPCError("CONFLICT", {
          message: "User with this email already exists",
        });
      }

      // Create user with proper fields - id should be auto-generated by the repository
      // Remove 'id' from the input as it should be auto-generated
      const userData = {
        name: input.name,
        email: input.email,
        password: input.password, // Should be hashed by repository
        role: input.role || "patient",
        createdAt: new Date(),
        updatedAt: new Date(),
      };

      const result = await authRepository.createUser({
        id: createId(),
        ...userData,
      });
      if (!result) {
        throw new ORPCError("INTERNAL_SERVER_ERROR", {
          message: "Registration failed. Please try again.",
        });
      }
      return result;
    } catch (error) {
      if (error instanceof ORPCError) throw error;
      throw new ORPCError("INTERNAL_SERVER_ERROR", {
        message: "Registration failed. Please try again.",
        cause: error,
      });
    }
  }),

  resetPassword: publicProcedure
    .input(resetPasswordSchema)
    .handler(async ({ input }) => {
      try {
        const user = await authRepository.findUserByEmail(input.email);
        if (!user) {
          return {
            success: true,
            message: "If an account exists, a reset email has been sent",
          };
        }

        // Use auth.api for password reset if available
        try {
          // Try using the auth API for password reset
          await auth.api.sendVerificationEmail({
            body: { email: input.email },
          });
          return {
            success: true,
            message: "Password reset email sent successfully",
          };
        } catch {
          // Fallback: Use repository method if available, or generate token manually
          const token = createId();
          const resetToken = await authRepository.createPasswordResetToken(
            user.id,
            token,
            new Date(Date.now() + 60 * 60 * 1000)
          );
          // In a real app, you would send an email here with the token
          // For now, return success
          return {
            success: true,
            message: "Password reset email sent successfully",
            token: resetToken.value, // Only for development - remove in production
          };
        }
      } catch (error) {
        if (error instanceof ORPCError) throw error;
        throw new ORPCError("INTERNAL_SERVER_ERROR", {
          message: "Failed to send reset email. Please try again.",
          cause: error,
        });
      }
    }),

  verifyEmail: publicProcedure
    .input(z.object({ token: z.string() }))
    .handler(async ({ input }) => {
      try {
        // Use repository method if available
        const result = await authRepository.verifyUserEmail(input.token);
        if (!result) {
          throw new ORPCError("BAD_REQUEST", {
            message: "Invalid or expired verification token",
          });
        }
        return {
          success: true,
          message: "Email verified successfully",
        };
      } catch (error) {
        if (error instanceof ORPCError) throw error;
        throw new ORPCError("INTERNAL_SERVER_ERROR", {
          message: "Failed to verify email. Please try again.",
          cause: error,
        });
      }
    }),

  // ─── Authenticated Routes ───

  logout: publicProcedure.handler(async ({ context }) => {
    try {
      // Use auth.api for logout if available
      if (context.session) {
        await auth.api.signOut({
          headers: context.request?.headers,
        });
      }
      return { success: true };
    } catch (error) {
      throw new ORPCError("INTERNAL_SERVER_ERROR", {
        message: "Logout failed. Please try again.",
        cause: error,
      });
    }
  }),

  changePassword: publicProcedure
    .input(changePasswordSchema)
    .handler(async ({ input, context }) => {
      try {
        // Handle null user
        if (!context.session?.user) {
          throw new ORPCError("UNAUTHORIZED", {
            message: "User not found",
          });
        }

        // Use repository method if available
        const result = await authRepository.updateUserPassword(
          context.session?.user.id,
          input.newPassword
        );
        if (!result) {
          throw new ORPCError("UNAUTHORIZED", {
            message: "Current password is incorrect",
          });
        }
        return {
          success: true,
          message: "Password changed successfully",
        };
      } catch (error) {
        if (error instanceof ORPCError) throw error;
        throw new ORPCError("INTERNAL_SERVER_ERROR", {
          message: "Failed to change password. Please try again.",
          cause: error,
        });
      }
    }),

  updateUser: publicProcedure
    .input(updateUserSchema)
    .handler(async ({ input, context }) => {
      try {
        if (!context.session?.user) {
          throw new ORPCError("UNAUTHORIZED", {
            message: "User not found",
          });
        }

        const result = await authRepository.updateUser(
          context.session?.user.id,
          input
        );
        if (!result) {
          throw new ORPCError("NOT_FOUND", {
            message: "User not found",
          });
        }
        return result;
      } catch (error) {
        if (error instanceof ORPCError) throw error;
        throw new ORPCError("INTERNAL_SERVER_ERROR", {
          message: "Failed to update user. Please try again.",
          cause: error,
        });
      }
    }),

  getSession: publicProcedure.handler(async ({ context }) => {
    try {
      if (!context.session?.user) {
        throw new ORPCError("UNAUTHORIZED", {
          message: "Session invalid",
        });
      }

      const user = await authRepository.findUserById(context.session?.user.id);
      if (!user) {
        throw new ORPCError("UNAUTHORIZED", {
          message: "Session invalid",
        });
      }
      return { user, session: context.session };
    } catch (error) {
      if (error instanceof ORPCError) throw error;
      throw new ORPCError("INTERNAL_SERVER_ERROR", {
        message: "Failed to get session. Please try again.",
        cause: error,
      });
    }
  }),

  setupTwoFactor: publicProcedure.handler(async ({ context }) => {
    try {
      if (!context.session?.user) {
        throw new ORPCError("UNAUTHORIZED", {
          message: "User not found",
        });
      }

      // Fetch full user from database to access custom fields
      const fullUser = await authRepository.findUserById(
        context.session?.user.id
      );
      if (!fullUser) {
        throw new ORPCError("NOT_FOUND", {
          message: "User not found",
        });
      }

      if (fullUser.twoFactorEnabled) {
        throw new ORPCError("BAD_REQUEST", {
          message: "2FA is already enabled",
        });
      }

      const twoFactorData = await authRepository.generateTwoFactorSecret(
        context.session?.user.id,
        createId(),
        JSON.stringify(Array.from({ length: 10 }, () => createId()))
      );

      return twoFactorData;
    } catch (error) {
      if (error instanceof ORPCError) throw error;
      throw new ORPCError("INTERNAL_SERVER_ERROR", {
        message: "Failed to setup 2FA. Please try again.",
        cause: error,
      });
    }
  }),

  verifyTwoFactor: publicProcedure
    .input(twoFactorVerifySchema)
    .handler(async ({ input, context }) => {
      try {
        if (!context.session?.user) {
          throw new ORPCError("UNAUTHORIZED", {
            message: "User not found",
          });
        }

        // Verify the 2FA token
        const isValid = await authRepository.verifyTwoFactorToken(
          context.session?.user.id,
          input.token
        );
        if (!isValid) {
          throw new ORPCError("BAD_REQUEST", {
            message: "Invalid 2FA token",
          });
        }
        return {
          success: true,
          message: "2FA enabled successfully",
        };
      } catch (error) {
        if (error instanceof ORPCError) throw error;
        throw new ORPCError("INTERNAL_SERVER_ERROR", {
          message: "Failed to verify 2FA. Please try again.",
          cause: error,
        });
      }
    }),

  disableTwoFactor: publicProcedure
    .input(twoFactorDisableSchema)
    .handler(async ({ context }) => {
      try {
        if (!context.session?.user) {
          throw new ORPCError("UNAUTHORIZED", {
            message: "User not found",
          });
        }

        // Disable 2FA with verification
        const result = await authRepository.disableTwoFactorAuth(
          context.session?.user.id
        );
        if (!result) {
          throw new ORPCError("BAD_REQUEST", {
            message: "Invalid 2FA token",
          });
        }
        return {
          success: true,
          message: "2FA disabled successfully",
        };
      } catch (error) {
        if (error instanceof ORPCError) throw error;
        throw new ORPCError("INTERNAL_SERVER_ERROR", {
          message: "Failed to disable 2FA. Please try again.",
          cause: error,
        });
      }
    }),

  // ─── Admin Routes ───
  listUsers: adminProcedure
    .input(
      z.object({
        limit: z.number().min(1).max(100).default(50),
        offset: z.number().min(0).default(0),
        search: z.string().optional(),
        role: z.enum(["admin", "doctor", "staff", "patient"]).optional(),
        status: z.enum(["active", "inactive", "suspended"]).optional(),
      })
    )
    .handler(async ({ input }) => {
      try {
        const result = await authRepository.findUsers({
          limit: input.limit,
          offset: input.offset,
          search: input.search,
          role: input.role,
          status: input.status,
        });
        return result;
      } catch (error) {
        throw new ORPCError("INTERNAL_SERVER_ERROR", {
          message: "Failed to fetch users",
          cause: error,
        });
      }
    }),
  getUserById: adminProcedure.input(z.string()).handler(async ({ input }) => {
    try {
      const user = await authRepository.findUserById(input);
      if (!user) {
        throw new ORPCError("NOT_FOUND", {
          message: "User not found",
        });
      }
      return user;
    } catch (error) {
      if (error instanceof ORPCError) throw error;
      throw new ORPCError("INTERNAL_SERVER_ERROR", {
        message: "Failed to fetch user",
        cause: error,
      });
    }
  }),

  updateUserRole: adminProcedure
    .input(
      z.object({
        userId: z.string(),
        role: z.enum(["admin", "doctor", "staff", "patient"]),
      })
    )
    .handler(async ({ input }) => {
      try {
        const result = await authRepository.updateUser(input.userId, {
          role: input.role,
        });
        if (!result) {
          throw new ORPCError("NOT_FOUND", {
            message: "User not found",
          });
        }
        return result;
      } catch (error) {
        if (error instanceof ORPCError) throw error;
        throw new ORPCError("INTERNAL_SERVER_ERROR", {
          message: "Failed to update user role",
          cause: error,
        });
      }
    }),

  suspendUser: adminProcedure
    .input(
      z.object({
        userId: z.string(),
        reason: z.string().optional(),
      })
    )
    .handler(async ({ input }) => {
      try {
        const result = await authRepository.updateUser(input.userId, {
          status: "suspended",
          banReason: input.reason,
          banned: true,
        });
        if (!result) {
          throw new ORPCError("NOT_FOUND", {
            message: "User not found",
          });
        }
        return result;
      } catch (error) {
        if (error instanceof ORPCError) throw error;
        throw new ORPCError("INTERNAL_SERVER_ERROR", {
          message: "Failed to suspend user",
          cause: error,
        });
      }
    }),

  activateUser: adminProcedure.input(z.string()).handler(async ({ input }) => {
    try {
      const result = await authRepository.updateUser(input, {
        status: "active",
        banned: false,
        banReason: "",
      });
      if (!result) {
        throw new ORPCError("NOT_FOUND", {
          message: "User not found",
        });
      }
      return result;
    } catch (error) {
      if (error instanceof ORPCError) throw error;
      throw new ORPCError("INTERNAL_SERVER_ERROR", {
        message: "Failed to activate user",
        cause: error,
      });
    }
  }),

  deleteUser: adminProcedure.input(z.string()).handler(async ({ input }) => {
    try {
      const result = await authRepository.deleteUser(input);
      if (!result) {
        throw new ORPCError("NOT_FOUND", {
          message: "User not found",
        });
      }
      return { success: true, message: "User deleted successfully" };
    } catch (error) {
      if (error instanceof ORPCError) throw error;
      throw new ORPCError("INTERNAL_SERVER_ERROR", {
        message: "Failed to delete user",
        cause: error,
      });
    }
  }),

  getAuditLogs: adminProcedure
    .input(
      z.object({
        limit: z.number().min(1).max(100).default(50),
        offset: z.number().min(0).default(0),
        userId: z.string().optional(),
        action: z
          .enum([
            "CREATE",
            "UPDATE",
            "DELETE",
            "VIEW",
            "EXPORT",
            "LOGIN",
            "RESTORE",
          ])
          .optional(),
        startDate: z.date().optional(),
        endDate: z.date().optional(),
      })
    )
    .handler(async ({ input }) => {
      try {
        const result = await authRepository.findAuditLogs({
          limit: input.limit,
          offset: input.offset,
          action: input.action,
          startDate: input.startDate,
          endDate: input.endDate,
        });
        return result;
      } catch (error) {
        if (error instanceof ORPCError) throw error;
        throw new ORPCError("INTERNAL_SERVER_ERROR", {
          message: "Failed to fetch audit logs",
          cause: error,
        });
      }
    }),
};
